export function dailyWordFor(date: Date, timeZone: string) {
  const key = new Intl.DateTimeFormat("en-CA", {
    timeZone,
    year: "numeric",
    month: "2-digit",
    day: "2-digit",
  }).format(date);
  const [year, month, day] = key.split("-").map(Number);
  const serialDay = Math.floor(Date.UTC(year, month - 1, day) / 86_400_000);
  // 37 and 200 are coprime, so all 200 messages appear before any repeats.
  return dailyWords[((serialDay * 37 + 17) % dailyWords.length + dailyWords.length) % dailyWords.length];
}
